import streamlit as st
import numpy as np
import pickle

# Load model
with open("cvd_model.pkl", "rb") as f:
    model = pickle.load(f)

st.title("🫀 CVD Risk Predictor")
st.markdown("Enter your health info to check your cardiovascular risk.")

# Example inputs — update according to your trained model’s feature order
age = st.slider("Age Group (1 = 18-24, ..., 13 = 80+)", 1, 13, 5)
bmi = st.number_input("BMI (e.g., 25.0)", 10.0, 50.0, step=0.1)
bmi = int(bmi * 100)  # convert to _BMI5 format
physhlth = st.slider("Physical Health - Poor days", 0, 30)
menthlth = st.slider("Mental Health - Poor days", 0, 30)
exerany2 = st.selectbox("Exercise (1=Yes, 2=No)", [1, 2])
smoke100 = st.selectbox("Smoked 100 cigarettes (1=Yes, 2=No)", [1, 2])
smokday2 = st.selectbox("Do you smoke now? (1=Every day, 2=Some days, 3=Not at all)", [1, 2, 3])
alcday4 = st.slider("Drinking days per month", 0, 30)
diabete4 = st.selectbox("Diabetes (1=Yes, 2=No, 3=Pre-diabetic)", [1, 2, 3])
cvdstrk3 = st.selectbox("Ever had a stroke? (1=Yes, 2=No)", [1, 2])
hadmam = st.selectbox("Ever had a mammogram? (1=Yes, 2=No)", [1, 2])
covidpos = st.selectbox("COVID positive? (1=Yes, 2=No)", [1, 2])
covidsmp = st.selectbox("Had COVID symptoms? (1=Yes, 2=No)", [1, 2])
covidprm = st.selectbox("Still experiencing COVID symptoms? (1=Yes, 2=No)", [1, 2])

# Combine inputs
input_data = np.array([[age, bmi, physhlth, menthlth, exerany2, smoke100, smokday2,
                        alcday4, diabete4, cvdstrk3, hadmam, covidpos, covidsmp, covidprm]])

# Predict
if st.button("Check CVD Risk"):
    prediction = model.predict(input_data)
    prob = model.predict_proba(input_data)[0][1]
    if prediction[0] == 1:
        st.error(f"⚠️ High Risk of CVD (Confidence: {prob:.2f})")
    else:
        st.success(f"✅ Low Risk of CVD (Confidence: {1 - prob:.2f})")